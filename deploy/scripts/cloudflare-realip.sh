#!/usr/bin/env bash
# Make nginx (and so the app's rate limits) see each visitor's real IP when the
# site sits behind Cloudflare, by trusting Cloudflare's published IP ranges.
#
#   sudo ./cloudflare-realip.sh          write /etc/nginx/conf.d/cloudflare-realip.conf, reload nginx
#   sudo ./cloudflare-realip.sh --ufw    also allow ports 80/443 from Cloudflare only
#
# Safe to re-run (for example monthly from cron) to pick up new ranges.
set -euo pipefail

v4=$(curl -fsS https://www.cloudflare.com/ips-v4)
v6=$(curl -fsS https://www.cloudflare.com/ips-v6)
if [ -z "$v4" ] || [ -z "$v6" ]; then
  echo "could not download Cloudflare IP ranges" >&2
  exit 1
fi

conf=/etc/nginx/conf.d/cloudflare-realip.conf
{
  echo "# Generated by cloudflare-realip.sh on $(date -u +%F). Re-run the script to update."
  for ip in $v4 $v6; do echo "set_real_ip_from $ip;"; done
  echo "real_ip_header CF-Connecting-IP;"
} > "$conf.tmp"
mv "$conf.tmp" "$conf"
nginx -t
systemctl reload nginx
echo "nginx trusts $(echo $v4 $v6 | wc -w) Cloudflare ranges"

if [ "${1:-}" = "--ufw" ]; then
  for ip in $v4 $v6; do
    ufw allow proto tcp from "$ip" to any port 80,443 comment 'Cloudflare' >/dev/null
  done
  ufw delete allow 'Nginx Full' >/dev/null 2>&1 || true
  echo "ufw: ports 80 and 443 now only accept connections from Cloudflare"
fi
